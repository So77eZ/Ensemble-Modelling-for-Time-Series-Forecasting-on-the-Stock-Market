# Длина входной последовательности (количество предыдущих торговых дней).
# Default используется Optuna при оптимизации гиперпараметров (HP, найденные
# на этой длине, применяются ко всем горизонтам как разумное приближение).
LSTM_LOOK_BACK: int = 30

# Per-horizon look_back (v16-experiments, 17.05.2026): гибридная конфигурация.
# Эксперимент показал что длинный контекст (LB=60) сильно улучшает h=3
# (DA +25pp, IC +0.42), но регрессирует h=1 (DA −17pp). Промежуточный
# LB=45 для h=2 даёт регрессию даже с per-horizon Optuna (DA 58→33).
# Гибрид: оставляем baseline LB=30 для h=1 и h=2 (где было хорошо),
# применяем LB=60 только для h=3 (где было слабо). Per-horizon HP только
# для h=3 (SBER_h3_hyperparams.json), для h=1,h=2 — общий SBER_hyperparams.json.
LSTM_LOOK_BACK_PER_HORIZON: dict = {1: 30, 2: 30, 3: 60}

